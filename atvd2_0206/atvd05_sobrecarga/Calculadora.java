public class Calculadora {
    
    public int somar(int n1, int n2) {
		return n1 + n2;
	}
	
	public double somar(double n1, double n2) {
		return n1 + n2;
	}

	public double somar(double n1, double n2, double n3) {
		return n1 + n2 + n3;
	}

    public double somar(double n1, double n2, double n3, double n4){
        return n1 + n2 + n3 + n4;
    }
    
    
    public int subtrair(int n1, int n2){
        return n1 - n2;
    }
    
    public double subtrair(double n1, double n2){
        return n1 - n2;
    }
    
    public double subtrair(double n1, double n2, double n3){
        return n1 - n2 - n3;
    }
    
    public double subtrair(double n1, double n2, double n3, double n4){
        return n1 - n2 - n3 - n4;
    }
    
    
    public double multiplicar(double n1, double n2){
        return n1 * n2;
    }
    
    public int multiplicar(int n1, int n2, int n3){
        return n1 * n2 * n3;
    }
    
    public double multiplicar(double n1, double n2, double n3, double n4){
        return n1 * n2 * n3 * n4;
    }
    
    
    public int dividir(int n1, int n2){
        return n1 / n2;
    }
    
    public double dividir(double n1, double n2, double n3){
        return n1 / n2 / n3;
    }
    
    public double dividir(double n1, double n2, double n3, double n4){
        return n1 / n2 / n3 / n4;
    }

}
